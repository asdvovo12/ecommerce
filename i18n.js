// لغة الجهاز (متوافقة مع نسخ expo-localization القديمة والجديدة)
const getDeviceLanguage = () => {
  try {
    if (typeof Localization.getLocales === 'function') {
      const locales = Localization.getLocales();
      if (locales && locales.length > 0) {
        return locales[0].languageCode || 'en';
      }
    }
    if (Localization.locale) {
      return Localization.locale.split('-')[0];
    }
  } catch (e) {
    console.warn('Could not detect device language:', e);
  }
  return 'en';
};

// ✅ init متزامن (synchronous)
i18n.use(initReactI18next).init({
  compatibilityJSON: 'v3',
  resources: {
    en: { translation: en },
    ar: { translation: ar },
  },
  lng: getDeviceLanguage() === 'ar' ? 'ar' : 'en',
  fallbackLng: 'en',
  interpolation: { escapeValue: false },
  react: { useSuspense: false },
});

// ✅ بعد الـ init، حمّل اللغة المحفوظة وغيّرها لو مختلفة
export const loadStoredLanguage = async () => {
  try {
    const stored = await AsyncStorage.getItem(LANGUAGE_KEY);
    if (stored && stored !== i18n.language) {
      await i18n.changeLanguage(stored);
    }
    return stored || i18n.language;
  } catch (error) {
    console.error('Error loading stored language:', error);
    return i18n.language;
  }
};

// ✅ دالة واحدة للحفظ + التغيير تستخدمها أي شاشة
export const changeAppLanguage = async (lng) => {
  await i18n.changeLanguage(lng);
  await AsyncStorage.setItem(LANGUAGE_KEY, lng);
};

loadStoredLanguage();

export default i18n;